// Documents the volunteer completes as a form: the PDF is generated by the
// form itself and saved for them, so there is no file to attach. `form` is the
// message type the form page posts back (…_pdf) and `formPage` is the page
// that hosts the form.
export const VOLUNTEER_FORM_DOCS = [
  { key: 'confidentiality_agreement', label: 'Confidentiality Agreement', bucket: 'onboarding-confidentiality',  urlKey: 'confidentiality_url', form: 'confidentiality_agreement', formPage: 'confidentiality_agreement.html', formWidth: 760 },
  { key: 'parking_pass',              label: 'Parking Pass',             bucket: 'onboarding-parking-passes', urlKey: 'parking_pass_url',     form: 'parking_pass',              formPage: 'parking_pass.html',              formWidth: 600 },
]

// Every document on the onboarding checklist, in display order.
export const VOLUNTEER_ONBOARDING_DOCS = [...VOLUNTEER_UPLOAD_DOCS, ...VOLUNTEER_FORM_DOCS]

const FORM_DOC_KEYS = VOLUNTEER_FORM_DOCS.map(d => d.key)

const NON_PATIENT_ROLES = ['Information Systems', 'Communications']

const DEFAULT_REQUIRED = ['background_check', 'id_check', 'immunization', 'tb_test']
const NON_PATIENT_ROLES_REQUIRED = ['background_check', 'id_check']
const MISSIONARY_REQUIRED = ['id_check']

export function hasSavedOnboardingPrefs(affiliation, defaultRole) {
  return !!affiliation && !!defaultRole
}

export function getRequiredDocKeys(affiliation, defaultRole) {
  if (affiliation === 'missionary') return MISSIONARY_REQUIRED
  if (NON_PATIENT_ROLES.includes(defaultRole)) return NON_PATIENT_ROLES_REQUIRED
  return DEFAULT_REQUIRED
}

export function isDocNotNeeded(itemKey, affiliation, defaultRole) {
  if (itemKey === 'licenses_certifications') return false
  // Form documents (parking pass, confidentiality agreement) apply to every
  // volunteer — they aren't part of the position-based required list.
  if (FORM_DOC_KEYS.includes(itemKey)) return false
  if (!hasSavedOnboardingPrefs(affiliation, defaultRole)) return false
  return !getRequiredDocKeys(affiliation, defaultRole).includes(itemKey)
}
